#!/usr/bin/env python3
"""OOXML（docx / xlsx / pptx）元数据清洗 —— 只依赖标准库。

为什么单独写这个模块，而不是把 watermarks-remover 的 ``container_meta.py``
原样搬进来
------------------------------------------------------------------------
上游 ``container_meta.py`` 有 4548 行，模块顶部就 import 了 ``av_meta``、
``image_meta``、``inspect_png`` 等一长串同目录模块，搬进来会拖出整个
service 依赖链；而其中真正和 docx 元数据相关的只有几十行。所以这里重写，
只保留必要逻辑，只依赖 ``zipfile`` 和 ``re``。

**清洗规则来源**：字段列表与跳过规则沿用上游 ``DOCX_SCRUB_FIELDS`` 的设计，
包括它踩过的两个坑（下面标注了对应 issue 号）。

为什么这一步必须放在流水线最后
------------------------------
``python-docx``、LibreOffice、Word 每次存盘都会**重写** ``docProps/``。
你在第一步清掉 ``dc:creator = python-docx``，只要后面任何一步用 python-docx
再 save 一次，这行就可能被写回来。所以元数据清洗只能在所有内容改动完成之后做。

设计原则
--------
1. **不删可见内容**：只动 ``docProps/``（文档属性）与特定的 ``customXml/``。
   正文 XML（``word/document.xml`` 等）一律不碰。
2. **保住 schema 合法性**：``AppVersion`` 不能清空。ECMA-376 Part 1
   §15.2.12.1 要求它匹配 ``\\d+\\.\\d{4}``，清空会让 Word 报"内容有问题"
   （上游 issue #283）。
3. **二进制部件字节保持**：``docProps/thumbnail.jpeg`` 等非 XML 部件原样保留，
   按 UTF-8 解码再编码会把字节变成 U+FFFD（上游 issue #312）。
4. **customXml 不无脑删**：Word 的参考文献库（``b:Sources``、"插入引文"功能）
   就存在 customXml 里，删掉会丢用户的引用数据。这里只删「空容器」，
   有内容的保留并报告。
"""

from __future__ import annotations

import io
import re
import zipfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

# ---------------------------------------------------------------------------
# 规则表
# ---------------------------------------------------------------------------

#: 一律清空的 provenance 字段（标签名 -> 报告中显示的名字）。
#:
#: 刻意**不清** ``dc:title``：它是文档自己的标题，不是生成痕迹。
#: 刻意**不清** ``AppVersion``：见模块文档第 2 条。
SCRUB_FIELDS: tuple[tuple[str, str], ...] = (
    ("dc:creator", "dc:creator（作者）"),
    ("cp:lastModifiedBy", "cp:lastModifiedBy（最后修改者）"),
    ("dc:description", "dc:description（说明）"),
    ("cp:keywords", "cp:keywords（关键词）"),
    ("dc:subject", "dc:subject（主题）"),
    ("cp:category", "cp:category（类别）"),
    ("Application", "Application（应用程序）"),
    ("Company", "Company（公司）"),
    ("Manager", "Manager（经理）"),
)

#: 生成器指纹：出现在这些位置就意味着文件是工具批量生成的。
GENERATOR_FINGERPRINTS: tuple[str, ...] = (
    "python-docx",
    "python-pptx",
    "openpyxl",
    "XlsxWriter",
    "docx4j",
    "pandoc",
    "LibreOffice",
    "aspose",
    "Aspose",
    "ReportLab",
    "generated by",
    "Aspose.Words",
)

#: 内容为空的 customXml 才算可删；有内容的（如 Word 参考文献库）保留。
RE_HAS_PAYLOAD = re.compile(r">\s*<[A-Za-z_:]")

#: 视为「只承载文档属性」的 zip 成员前缀。
META_PREFIXES = ("docProps/",)

#: python-docx / python-pptx 默认模板会写入的时间戳，是极显眼的批量生成指纹。
TEMPLATE_TIMESTAMPS: frozenset[str] = frozenset(
    {
        "2013-12-23T23:15:00Z",
        "2014-01-01T00:00:00Z",
        "2012-02-01T00:00:00Z",
    }
)


@dataclass
class MetaReport:
    """一次元数据检查/清洗的结果。"""

    path: str
    kind: str = ""  # docx | xlsx | pptx | odt | unknown
    findings: list[str] = field(default_factory=list)
    actions: list[str] = field(default_factory=list)
    #: 命中的生成器指纹 -> 出现位置
    generator_hits: dict[str, list[str]] = field(default_factory=dict)
    #: 有值但未清空的字段（例如被判定为业务数据而保留的）
    kept: list[str] = field(default_factory=list)
    clean: bool = True

    def to_dict(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "kind": self.kind,
            "clean": self.clean,
            "findings": self.findings,
            "actions": self.actions,
            "generator_hits": self.generator_hits,
            "kept": self.kept,
        }


# ---------------------------------------------------------------------------
# 格式判定
# ---------------------------------------------------------------------------


def detect_kind(names: list[str]) -> str:
    """按 zip 内的部件判断 OOXML 子类型。"""
    if "word/document.xml" in names:
        return "docx"
    if "xl/workbook.xml" in names:
        return "xlsx"
    if "ppt/presentation.xml" in names:
        return "pptx"
    if "content.xml" in names and "mimetype" in names:
        return "odt"
    return "unknown"


def _iter_tag_blocks(text: str, open_re: re.Pattern[str], close_re: re.Pattern[str]):
    """产出 (open_start, open_end, close_start, close_end)，用于定位标签块。"""
    for m in open_re.finditer(text):
        close = close_re.search(text, m.end())
        if close:
            yield m.start(), m.end(), close.start(), close.end()


def _blank_field(text: str, tag: str) -> tuple[str, int]:
    """把 ``<tag>任意内容</tag>`` 就地清空成 ``<tag></tag>``，返回 (新文本, 清了几处)。"""
    open_re = re.compile(rf"<{re.escape(tag)}\b[^>]*>", re.I)
    close_re = re.compile(rf"</{re.escape(tag)}\s*>", re.I)
    out: list[str] = []
    last = 0
    n = 0
    for os_, oe, cs_, ce in _iter_tag_blocks(text, open_re, close_re):
        out.append(text[last:oe])
        out.append(text[cs_:ce])
        last = ce
        if text[oe:cs_].strip():
            n += 1
    out.append(text[last:])
    return "".join(out), n


def _find_fingerprints(text: str, where: str, hits: dict[str, list[str]]) -> None:
    for fp in GENERATOR_FINGERPRINTS:
        if fp.lower() in text.lower():
            hits.setdefault(fp, []).append(where)


# ---------------------------------------------------------------------------
# 检查
# ---------------------------------------------------------------------------


def inspect_ooxml(data: bytes, path: str = "<bytes>") -> MetaReport:
    """只读检查：列出所有 provenance 痕迹，不改字节。"""
    rep = MetaReport(path=path)
    try:
        zf = zipfile.ZipFile(io.BytesIO(data))
    except zipfile.BadZipFile:
        rep.kind = "unknown"
        rep.clean = False
        rep.findings.append("不是合法的 zip 容器，无法按 OOXML 处理")
        return rep

    with zf:
        names = zf.namelist()
        rep.kind = detect_kind(names)

        for name in names:
            if not (name.startswith(META_PREFIXES) or name.startswith("customXml/")):
                continue
            if not name.lower().endswith((".xml", ".rels")):
                rep.findings.append(f"二进制属性部件（保持原样）：{name}")
                continue
            raw = zf.read(name)
            text = raw.decode("utf-8", errors="replace")
            _find_fingerprints(text, name, rep.generator_hits)

            # 字段有值就报告
            for tag, label in SCRUB_FIELDS:
                open_re = re.compile(rf"<{re.escape(tag)}\b[^>]*>", re.I)
                close_re = re.compile(rf"</{re.escape(tag)}\s*>", re.I)
                for _os, oe, cs, _ce in _iter_tag_blocks(text, open_re, close_re):
                    val = text[oe:cs].strip()
                    if val:
                        rep.findings.append(f"{name}: {label} = {val!r}")

            # customXml 里有内容就提醒（删了会丢引用库）
            if name.startswith("customXml/") and name.endswith(".xml") and RE_HAS_PAYLOAD.search(text):
                if name.endswith(".rels"):
                    rep.findings.append(f"{name}: 关系文件，随部件一并保留")
                else:
                    rep.findings.append(f"{name}: 含有实际数据，清洗时会保留（可能是 Word 参考文献库）")

        # 时间戳：只在「仍是模板默认值」时算作发现，避免清洗后自报残留
        for name in names:
            if name.endswith("docProps/core.xml"):
                text = zf.read(name).decode("utf-8", errors="replace")
                for stamp in ("dcterms:created", "dcterms:modified"):
                    m = re.search(rf"<{stamp}[^>]*>([^<]*)</{stamp}>", text)
                    if m and m.group(1).strip():
                        val = m.group(1).strip()
                        if val in TEMPLATE_TIMESTAMPS:
                            rep.findings.append(
                                f"{name}: {stamp} = {val}（模板默认值，清洗时会改成当前时间）"
                            )

    rep.clean = not rep.findings
    return rep


# ---------------------------------------------------------------------------
# 清洗
# ---------------------------------------------------------------------------


def clean_ooxml(
    data: bytes,
    *,
    path: str = "<bytes>",
    drop_customxml: bool = False,
    normalize_dates: bool = True,
) -> tuple[bytes, MetaReport]:
    """清洗 OOXML 的元数据，返回（新字节, 报告）。

    ``drop_customxml``：是否连有内容的 customXml 也删。默认 False，
    因为有内容的 customXml 往往是 Word 的参考文献库，删掉会丢用户的引用。
    """
    rep = MetaReport(path=path)
    try:
        zin = zipfile.ZipFile(io.BytesIO(data))
    except zipfile.BadZipFile:
        rep.kind = "unknown"
        rep.clean = False
        rep.findings.append("不是合法的 zip 容器")
        return data, rep

    src_infos = zin.infolist()
    rep.kind = detect_kind(zin.namelist())
    out_buf = io.BytesIO()

    #: 真正被删除的部件名。只有在这里面的，才允许从 [Content_Types].xml 里摘掉
    #: 对应 override —— 否则会造出「override 没了、部件还在」的 OPC 结构不一致，
    #: Word 能容忍，但严格校验器和 LibreOffice 转换会报错。
    dropped: set[str] = set()

    with zin, zipfile.ZipFile(out_buf, "w", zipfile.ZIP_DEFLATED) as zout:
        for info in src_infos:
            name = info.filename
            raw = zin.read(name)

            # ── 1. customXml：只在判定为「空壳」时删 ──
            if name.startswith("customXml/"):
                text = raw.decode("utf-8", errors="replace") if name.endswith(".xml") else ""
                empty = bool(name.endswith(".xml")) and not RE_HAS_PAYLOAD.search(text)
                if drop_customxml or empty:
                    rep.actions.append(
                        f"删除部件 {name}" + ("（强制）" if drop_customxml else "（空壳）")
                    )
                    dropped.add(name)
                    continue
                rep.kept.append(f"{name}（含数据，保留）")
                zout.writestr(info, raw)
                continue

            # ── 2. docProps：清字段 ──
            if name.startswith(META_PREFIXES):
                if not name.lower().endswith(".xml"):
                    # 二进制（缩略图等）原样写入，解码再编码会破坏字节
                    zout.writestr(info, raw)
                    continue
                text = raw.decode("utf-8", errors="surrogateescape")
                _find_fingerprints(text, name, rep.generator_hits)
                for tag, label in SCRUB_FIELDS:
                    new_text, n = _blank_field(text, tag)
                    if n:
                        text = new_text
                        rep.actions.append(f"清空 {name} 的 {label}")
                if name.endswith("core.xml") and normalize_dates:
                    text = _normalize_timestamps(text, rep)
                zout.writestr(info, text.encode("utf-8", errors="surrogateescape"))
                continue

            # ── 3. [Content_Types].xml：只摘掉「确实已删部件」的 override ──
            if name == "[Content_Types].xml":
                text = raw.decode("utf-8", errors="surrogateescape")
                for part in sorted(dropped):
                    pat = rf'<Override\b[^>]*PartName="/{re.escape(part)}"[^>]*/>'
                    new_text, n = re.subn(pat, "", text)
                    if n:
                        text = new_text
                        rep.actions.append(f"从 Content_Types 移除 {part} 的 override")
                zout.writestr(info, text.encode("utf-8", errors="surrogateescape"))
                continue

            # ── 4. 其他部件：原样 ──
            zout.writestr(info, raw)

    rep.findings = [f"生成器指纹：{k} 出现在 {', '.join(v)}" for k, v in rep.generator_hits.items()]
    rep.clean = not rep.actions
    return out_buf.getvalue(), rep


def _normalize_timestamps(text: str, rep: MetaReport) -> str:
    """把 core.xml 里明显是模板默认值的时间戳改成当前时间。

    为什么：python-docx 生成的 docx 固定写 ``2013-12-23T23:15:00Z``，
    这是个极度显眼的模板指纹——几十万份文件时间戳一模一样。改成当前时间
    并不能证明什么，但至少不主动暴露"我是脚本批量生成的"。
    """
    from datetime import datetime, timezone

    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    for stamp in ("dcterms:created", "dcterms:modified"):
        pat = re.compile(rf"<{stamp}([^>]*)>([^<]*)</{stamp}>")
        m = pat.search(text)
        if not m:
            continue
        old = m.group(2).strip()
        if old and old != now:
            text = pat.sub(rf"<{stamp}\1>{now}</{stamp}>", text, count=1)
            rep.actions.append(f"{stamp}: {old} → {now}")
    return text


# ---------------------------------------------------------------------------
# 文件级接口
# ---------------------------------------------------------------------------


def _write_with_backup(target: Path, data: bytes) -> Path:
    """写回目标文件，原文件留一份 .bak。返回备份路径。"""
    bak = target.with_suffix(target.suffix + ".bak")
    if not bak.exists():
        bak.write_bytes(target.read_bytes())
    target.write_bytes(data)
    return bak


def inspect_file(path: str | Path) -> MetaReport:
    p = Path(path)
    return inspect_ooxml(p.read_bytes(), path=str(p))


def clean_file(path: str | Path, *, output: str | Path | None = None, **kwargs: Any) -> MetaReport:
    p = Path(path)
    data, rep = clean_ooxml(p.read_bytes(), path=str(p), **kwargs)
    if output is None:
        _write_with_backup(p, data)
    else:
        Path(output).write_bytes(data)
    return rep


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    import argparse
    import json
    import sys

    ap = argparse.ArgumentParser(description="OOXML 元数据检查与清洗（docx/xlsx/pptx）")
    ap.add_argument("path", help="目标文件")
    ap.add_argument("--clean", action="store_true", help="执行清洗（默认只检查）")
    ap.add_argument("-o", "--output", help="清洗后输出到新文件（默认原地覆盖并留 .bak）")
    ap.add_argument("--drop-customxml", action="store_true", help="连有数据的 customXml 也删除")
    ap.add_argument("--json", action="store_true", help="输出 JSON")
    args = ap.parse_args(argv)

    if args.clean:
        rep = clean_file(args.path, output=args.output, drop_customxml=args.drop_customxml)
    else:
        rep = inspect_file(args.path)

    if args.json:
        print(json.dumps(rep.to_dict(), ensure_ascii=False, indent=2))
    else:
        tag = "清洗完成" if args.clean else "检查结果"
        print(f"=== {tag}：{rep.path}（{rep.kind}）===")
        if rep.findings:
            print("\n发现：")
            for f in rep.findings:
                print(f"  - {f}")
        if rep.actions:
            print("\n已执行：")
            for a in rep.actions:
                print(f"  - {a}")
        if rep.kept:
            print("\n保留：")
            for k in rep.kept:
                print(f"  - {k}")
        if not (rep.findings or rep.actions or rep.kept):
            print("  无可清洗的元数据痕迹。")

    return 1 if (not args.clean and rep.findings) else 0


if __name__ == "__main__":
    raise SystemExit(main())
